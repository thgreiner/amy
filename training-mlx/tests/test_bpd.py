"""Tests for the BPD format (de)serialization.

The reference data in tests/data/bpd_test.bin was generated by amy's
``bpd-test`` command (branch feature/binary-position-representation);
the EPDs below are the ones amy encodes (see bpd_test_epds in
amy/src/bpd.c).
"""

import numpy as np
import pytest

from amy_training_nnue.bpd import (
    BLACK,
    RECORD_SIZE,
    WHITE,
    BpdRecord,
    encode_board,
    read_records,
    square_name,
    write_records,
)
from amy_training_nnue.position import position_from_record

DATA = __file__.rsplit("/", 1)[0] + "/data/bpd_test.bin"

# (epd, score, turn) exactly as in amy's bpd_test_epds table.
EXPECTED = [
    ("rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq -", 1, WHITE),
    ("rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR b KQkq -", 2, BLACK),
    ("rnbqkbnr/pppp1ppp/8/4p3/4P3/5N2/PPPP1PPP/RNBQKB1R w KQkq -", 3, WHITE),
    ("4k3/8/8/8/8/8/8/R3K3 w - -", 4, WHITE),
    ("r3k2r/8/8/8/8/8/8/4K3 b - -", 5, BLACK),
]


def test_record_size():
    assert RECORD_SIZE == 40


def test_file_size():
    with open(DATA, "rb") as f:
        size = f.seek(0, 2)
    assert size == 5 * RECORD_SIZE


def test_decode_amy_test_data():
    records = list(read_records(DATA))
    assert len(records) == 5
    for record, (epd, score, turn) in zip(records, EXPECTED):
        assert record.score == score
        assert record.turn == turn
        assert record.validate() == []
        pos = position_from_record(record)
        assert pos.epd() == epd


def test_roundtrip():
    records = list(read_records(DATA))
    write_records("/tmp/rt.bpd", records)
    again = list(read_records("/tmp/rt.bpd"))
    for a, b in zip(records, again):
        assert a.pos == b.pos
        assert a.score == b.score
        assert a.turn == b.turn
        assert a.encode() == b.encode()


def test_square_names():
    assert square_name(0) == "a1"
    assert square_name(7) == "h1"
    assert square_name(8) == "a2"
    assert square_name(63) == "h8"


def test_board_decode_initial():
    (record,) = [r for r in read_records(DATA) if r.score == 1]
    board = record.board()
    assert (board == 1).sum() == 8  # white pawns
    assert (board == -1).sum() == 8  # black pawns
    assert (board == 6).sum() == 1
    assert (board == -6).sum() == 1
    assert board[4] == 6  # white king e1
    assert board[60] == -6  # black king e8


def test_encode_decode_castling_and_ep():
    from amy_training_nnue.position import (
        CASTLE_BK,
        CASTLE_BQ,
        CASTLE_WK,
        CASTLE_WQ,
    )

    (record,) = [r for r in read_records(DATA) if r.score == 1]
    board = record.board()
    epd = position_from_record(record)
    encoded = encode_board(
        board,
        WHITE,
        record.score,
        castle=CASTLE_WQ | CASTLE_WK | CASTLE_BQ | CASTLE_BK,
        ep=-1,
    )
    assert encoded.encode() == record.encode()
    assert position_from_record(encoded).epd() == epd.epd()

    # En passant: black pawn just played d7-d5 (d5 sq 35), white pawn
    # on e5 (sq 36), ep target d6 (sq 43, rank 6).
    board = np.zeros(64, dtype=np.int8)
    board[4] = 6  # white king e1
    board[36] = 1  # white pawn e5
    board[35] = -1  # black pawn d5
    board[60] = -6  # black king e8
    rec = encode_board(board, WHITE, 0, ep=43)
    assert rec.validate() == []
    assert position_from_record(rec).epd() == ("4k3/8/8/3pP3/8/8/8/4K3 w - d6")
    assert rec.encode() == encode_board(board, WHITE, 0, ep=43).encode()


def test_validate_missing_king():
    pos = [0] * 4
    # only a white king on a1
    pos[0] = 7
    rec = BpdRecord(tuple(pos), 0, WHITE)
    problems = rec.validate()
    assert any("black king" in p for p in problems)


def test_validate_double_king():
    pos = [0] * 4
    pos[0] = 7 | (7 << 4)  # two white kings a1, b1
    pos[3] = 14  # black king a8
    rec = BpdRecord(tuple(pos), 0, WHITE)
    problems = rec.validate()
    assert any("white king" in p for p in problems)


def test_validate_bad_turn():
    rec = BpdRecord((0, 0, 0, 0), 0, 3)
    assert any("turn" in p for p in rec.validate())


def test_bad_file_size():
    import tempfile

    with tempfile.NamedTemporaryFile(suffix=".bin") as f:
        f.write(b"\x00" * (RECORD_SIZE + 1))
        f.flush()
        with pytest.raises(ValueError, match="multiple"):
            list(read_records(f.name))
